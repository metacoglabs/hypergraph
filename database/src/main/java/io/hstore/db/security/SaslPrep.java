    private SaslPrep() {
    }

    static String prepare(String password) {
        if (password.chars().allMatch(c -> c < 0x80)) {
            return password;
        }
        int[] mapped = password.codePoints()
                .filter(code -> !MAPPED_TO_NOTHING.contains(code) || NON_ASCII_SPACE.contains(code))
                .map(code -> NON_ASCII_SPACE.contains(code) ? ' ' : code)
                .toArray();
        if (mapped.length == 0 || Arrays.stream(mapped).anyMatch(UNASSIGNED::contains)) {
            return password;
        }
        String normalized = Normalizer.normalize(new String(mapped, 0, mapped.length), Normalizer.Form.NFKC);
        int[] codes = normalized.codePoints().toArray();
        if (Arrays.stream(codes).anyMatch(code -> PROHIBITED.contains(code) || code >= 0xD800 && code <= 0xDFFF || UNASSIGNED.contains(code))) {
            return password;
        }
        if (Arrays.stream(codes).anyMatch(RAND_AL_CAT::contains)
                && (Arrays.stream(codes).anyMatch(L_CAT::contains) || !RAND_AL_CAT.contains(codes[0]) || !RAND_AL_CAT.contains(codes[codes.length - 1]))) {
            return password;
        }
        return normalized;
    }

    private record Ranges(int[] starts, int[] ends) {
        static Ranges parse(String text) {
            String[] parts = text.split(",");
            int[] starts = new int[parts.length];
            int[] ends = new int[parts.length];
            for (int i = 0; i < parts.length; i++) {
                int dash = parts[i].indexOf('-');
                starts[i] = Integer.parseInt(dash < 0 ? parts[i] : parts[i].substring(0, dash), 16);
                ends[i] = dash < 0 ? starts[i] : Integer.parseInt(parts[i].substring(dash + 1), 16);
            }
            return new Ranges(starts, ends);
        }

        boolean contains(int code) {
            int at = Arrays.binarySearch(starts, code);
            int range = at >= 0 ? at : -at - 2;
            return range >= 0 && code <= ends[range];
        }
    }
